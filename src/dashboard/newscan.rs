//! The New Scan engagement builder: turn a human's target list into a validated
//! engagement file. Pure validation + YAML construction live here; the axum
//! handler (in the dashboard binary) does the IO.
//!
//! Every target is checked with [`crate::scope::classify_target`] — the same
//! strict parser the `ScopeGuard` enforces — so an engagement this builds can
//! only ever contain targets that are in its own scope. Defining a scan never
//! widens what Ascent is allowed to touch, and it never runs anything: it writes
//! a scope file that the pipeline (and its approval gates) still gate at run time.

use crate::scope::classify_target;
use serde::{Deserialize, Serialize};

/// The POSTed New Scan form.
#[derive(Debug, Deserialize)]
pub struct NewScanRequest {
    #[serde(default)]
    pub name: String,
    /// Raw target lines: hostnames, IP literals, CIDRs or URLs.
    #[serde(default)]
    pub targets: Vec<String>,
    /// Optional source root that enables the white-box SAST track.
    #[serde(default)]
    pub source: String,
}

/// A validated engagement ready to be written to disk.
#[derive(Debug, PartialEq, Eq)]
pub struct Prepared {
    pub name: String,
    pub slug: String,
    pub hosts: Vec<String>,
    pub cidrs: Vec<String>,
    pub urls: Vec<String>,
    pub source: String,
    pub yaml: String,
}

/// Why a New Scan request was refused. Nothing is written for any of these.
#[derive(Debug, PartialEq, Eq)]
pub enum PrepareError {
    /// The name was empty or whitespace.
    EmptyName,
    /// The name has no letters or digits, so it has no safe file slug.
    UnusableName,
    /// One or more raw target lines were not valid, unambiguous scope entries.
    /// Carries the rejected raw lines, in input order.
    RejectedTargets(Vec<String>),
    /// No valid targets remained.
    NoTargets,
    /// A non-empty source path that does not exist as a directory.
    SourceNotFound(String),
    /// The validated engagement could not be serialized (should not happen).
    Internal(String),
}

/// Lowercase slug of `[a-z0-9-]`, collapsing other runs to a single `-` and
/// trimming leading/trailing `-`. Capped at 64 chars. Empty if the name has no
/// alphanumerics. This is the sole source of the on-disk filename, so by
/// construction it can never contain a path separator, `.`, or `..`.
fn slugify(name: &str) -> String {
    let mut out = String::new();
    let mut prev_dash = false;
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
            prev_dash = false;
        } else if !out.is_empty() && !prev_dash {
            out.push('-');
            prev_dash = true;
        }
        if out.len() >= 64 {
            break;
        }
    }
    while out.ends_with('-') {
        out.pop();
    }
    out
}

#[derive(Serialize)]
struct EngagementFile<'a> {
    name: &'a str,
    hosts: &'a [String],
    cidrs: &'a [String],
    urls: &'a [String],
    #[serde(skip_serializing_if = "str::is_empty")]
    source: &'a str,
    starts: &'a str,
    ends: &'a str,
}

const HEADER: &str = "\
# Generated by the Ascent dashboard (New Scan).
# AUTHORISED TARGETS ONLY: every host, network and URL below was entered as
# in-scope for this engagement. Review before running. Running is a separate,
# explicit step, and every exploit action still requires human approval.
";

/// Validate a New Scan request and build the engagement YAML. Pure:
/// `source_exists` is injected so this is testable without touching the
/// filesystem, and the two timestamps are supplied by the caller.
pub fn prepare(
    req: &NewScanRequest,
    starts: &str,
    ends: &str,
    source_exists: &dyn Fn(&str) -> bool,
) -> Result<Prepared, PrepareError> {
    let name = req.name.trim();
    if name.is_empty() {
        return Err(PrepareError::EmptyName);
    }
    let slug = slugify(name);
    if slug.is_empty() {
        return Err(PrepareError::UnusableName);
    }

    let mut hosts = Vec::new();
    let mut cidrs = Vec::new();
    let mut urls = Vec::new();
    let mut rejected = Vec::new();
    for raw in &req.targets {
        if raw.trim().is_empty() {
            continue; // blank lines in the textarea are ignored, not rejected
        }
        match classify_target(raw) {
            Some(("hosts", v)) => hosts.push(v),
            Some(("cidrs", v)) => cidrs.push(v),
            Some(("urls", v)) => urls.push(v),
            Some(_) => unreachable!("classify_target only yields hosts/cidrs/urls"),
            None => rejected.push(raw.trim().to_string()),
        }
    }
    // Fail closed: if any single target is bad we write nothing and report them
    // all, so the human fixes the scope rather than silently losing a target.
    if !rejected.is_empty() {
        return Err(PrepareError::RejectedTargets(rejected));
    }
    if hosts.is_empty() && cidrs.is_empty() && urls.is_empty() {
        return Err(PrepareError::NoTargets);
    }

    let source = req.source.trim().to_string();
    if !source.is_empty() && !source_exists(&source) {
        return Err(PrepareError::SourceNotFound(source));
    }

    let body = EngagementFile {
        name,
        hosts: &hosts,
        cidrs: &cidrs,
        urls: &urls,
        source: &source,
        starts,
        ends,
    };
    let yaml = serde_yaml_ng::to_string(&body).map_err(|e| PrepareError::Internal(e.to_string()))?;
    let yaml = format!("{HEADER}{yaml}");

    Ok(Prepared {
        name: name.to_string(),
        slug,
        hosts,
        cidrs,
        urls,
        source,
        yaml,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const STARTS: &str = "2026-01-01T00:00:00.000000+00:00";
    const ENDS: &str = "2027-01-01T00:00:00.000000+00:00";

    fn req(name: &str, targets: &[&str], source: &str) -> NewScanRequest {
        NewScanRequest {
            name: name.into(),
            targets: targets.iter().map(|s| s.to_string()).collect(),
            source: source.into(),
        }
    }

    fn prep(r: &NewScanRequest) -> Result<Prepared, PrepareError> {
        prepare(r, STARTS, ENDS, &|_| true)
    }

    #[test]
    fn slugify_is_filename_safe() {
        assert_eq!(slugify("Acme Q4 Test!"), "acme-q4-test");
        assert_eq!(slugify("  weird//name..  "), "weird-name");
        assert_eq!(slugify("../../etc/passwd"), "etc-passwd");
        assert_eq!(slugify("!!!"), "");
        assert_eq!(slugify("a").len(), 1);
        assert!(slugify(&"x".repeat(200)).len() <= 64);
        // never a path separator or dot
        let s = slugify("a/b\\c.d");
        assert!(!s.contains(['/', '\\', '.']));
    }

    #[test]
    fn empty_and_unusable_names_are_refused() {
        assert_eq!(prep(&req("   ", &["example.com"], "")), Err(PrepareError::EmptyName));
        assert_eq!(prep(&req("!!!", &["example.com"], "")), Err(PrepareError::UnusableName));
    }

    #[test]
    fn blank_target_lines_are_ignored_not_rejected() {
        let p = prep(&req("Acme", &["example.com", "  ", ""], "")).unwrap();
        assert_eq!(p.hosts, vec!["example.com".to_string()]);
    }

    #[test]
    fn all_blank_targets_is_no_targets() {
        assert_eq!(prep(&req("Acme", &["", "   "], "")), Err(PrepareError::NoTargets));
        assert_eq!(prep(&req("Acme", &[], "")), Err(PrepareError::NoTargets));
    }

    #[test]
    fn one_bad_target_rejects_the_whole_request() {
        // A good + bad mix writes nothing and names every bad entry.
        let err = prep(&req("Acme", &["example.com", "evil.com/path", "exa mple.com"], "")).unwrap_err();
        assert_eq!(
            err,
            PrepareError::RejectedTargets(vec!["evil.com/path".into(), "exa mple.com".into()])
        );
    }

    #[test]
    fn source_must_exist_when_provided() {
        let r = req("Acme", &["example.com"], "./no-such-src");
        assert_eq!(
            prepare(&r, STARTS, ENDS, &|_| false),
            Err(PrepareError::SourceNotFound("./no-such-src".into()))
        );
        // when it exists, it lands in the engagement
        let p = prepare(&r, STARTS, ENDS, &|_| true).unwrap();
        assert_eq!(p.source, "./no-such-src");
        assert!(p.yaml.contains("source: ./no-such-src"));
    }

    #[test]
    fn empty_source_is_omitted_from_yaml() {
        let p = prep(&req("Acme", &["example.com"], "  ")).unwrap();
        assert_eq!(p.source, "");
        assert!(!p.yaml.contains("source:"));
    }

    #[test]
    fn targets_are_bucketed_and_canonicalised() {
        let p = prep(&req(
            "Mixed",
            &["Example.COM", "10.0.0.0/24", "http://localhost:3000/"],
            "",
        ))
        .unwrap();
        assert_eq!(p.hosts, vec!["example.com".to_string()]);
        assert_eq!(p.cidrs, vec!["10.0.0.0/24".to_string()]);
        assert_eq!(p.urls, vec!["http://localhost:3000/".to_string()]);
    }

    /// The core safety property, end to end: the YAML this builds parses back into
    /// an Engagement whose ScopeGuard considers exactly the entered targets in
    /// scope — and nothing else. A generated scan can never be broader than typed.
    #[test]
    fn generated_yaml_parses_and_is_scoped_to_the_entered_targets() {
        let p = prep(&req(
            "Acme Q4 Test!",
            &["example.com", "10.0.0.0/24", "http://localhost:3000/", ""],
            "",
        ))
        .unwrap();
        assert_eq!(p.slug, "acme-q4-test");
        assert!(p.yaml.starts_with("# Generated by the Ascent dashboard"));

        let eng: crate::scope::Engagement =
            serde_yaml_ng::from_str(&p.yaml).expect("generated engagement must parse");
        let g = crate::scope::ScopeGuard::new(&eng);
        assert!(g.in_scope("example.com"));
        assert!(g.in_scope("sub.example.com"));
        assert!(g.in_scope("10.0.0.5"));
        assert!(g.in_scope("http://localhost:3000/login"));
        // and nothing outside the entered scope
        assert!(!g.in_scope("evil.com"));
        assert!(!g.in_scope("10.0.1.5"));
        assert!(!g.in_scope("8.8.8.8"));
    }
}
